package com.redelar.bluestempo.model

/**
 * Músicas para praticar: a setlist (com a numeração da lista do usuário), os extras e as que saíram
 * da setlist (guardadas, mas fora da navegação "anterior/próxima").
 *
 * Cifra: compassos separados por `|`, acordes do compasso separados por espaço (dividem o
 * compasso em partes iguais; repita o acorde para durações diferentes, ex. `G G G C`).
 * `%` repete o compasso anterior, `*4` no fim do compasso repete-o 4 vezes e `[2]` no
 * começo dá ao compasso só 2 tempos. Na forma, `Refrão x2` toca a seção duas vezes.
 */
object SongBook {

    val all: List<Song> = SONGS.map { it.build() }

    private val byId: Map<String, Song> = all.associateBy { it.id }

    fun byId(id: String?): Song? = id?.let { byId[it] }
}

private class SongSpec(
    val number: Int,
    val id: String,
    val title: String,
    val artist: String,
    val reference: String,
    val key: String,
    val bpm: Int,
    val groove: String,
    val bass: BassStyle?,
    val swing: Float?,
    val group: SongGroup,
    val confidence: Confidence,
    val notes: String,
    val form: String,
    val sections: List<Pair<String, String>>,
) {
    fun build(): Song {
        val (tonic, minor) = ChordParser.parseKey(key)
        require(GrooveLibrary.byId(groove).id == groove) { "Música $id: levada desconhecida $groove" }
        val parsed = sections.map { (name, text) -> SongSection(name, ChordParser.parseBars(text, tonic)) }
        val byName = parsed.associateBy { it.name }
        val order = form.split(',').map { it.trim() }.filter { it.isNotEmpty() }.flatMap { token ->
            val m = Regex("^(.*?)\\s+x(\\d+)$").matchEntire(token)
            val name = m?.groupValues?.get(1) ?: token
            val times = m?.groupValues?.get(2)?.toInt() ?: 1
            val section = byName[name] ?: error("Música $id: seção \"$name\" não existe")
            List(times) { section }
        }
        return Song(
            id = id, number = number, title = title, artist = artist, reference = reference,
            key = tonic, minor = minor, bpm = bpm, grooveId = groove, bassStyle = bass, swing = swing,
            sections = parsed, form = order, notes = notes, confidence = confidence, group = group,
        )
    }
}

